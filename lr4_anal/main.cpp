/**
 * @file main.cpp
 * @brief ЛР4. Дискретная задача управления запасами. Вариант 4.
 *
 * @details
 * Рассматривается дискретная задача управления запасами на n = 4 месяца.
 *
 * Дано:
 *   - k0 — начальный запас;
 *   - kn = k4 — требуемый запас после последнего месяца;
 *   - y_i — расход (спрос) в i-м месяце, i = 1..n;
 *   - φ(z) — затраты на хранение при среднем запасе z;
 *   - ψ(x) — затраты на пополнение в объёме x.
 *
 * В файле варианта функции обозначены как j(z) и y(z):
 *   j(z) — это φ(z), стоимость хранения;
 *   y(z) — это ψ(z), стоимость пополнения.
 *
 * Модель:
 *   k_i = k_{i-1} + x_i - y_i,   k_i >= 0,
 *   где k_i — запас в конце i-го месяца,
 *       x_i — объём пополнения в i-м месяце (целое неотрицательное число).
 *
 * Средний запас за месяц, к которому применяется стоимость хранения:
 *   z = (k_{i-1} + k_i + y_i) / 2.
 *
 * Суммарные затраты:
 *   Σ [ φ(z_i) + ψ(x_i) ]  ->  min.
 *
 * Метод решения: динамическое программирование по месяцам.
 *
 * Рекуррентное соотношение:
 *   Q_0(k0) = 0;
 *   Q_i(k_i) = min { Q_{i-1}(k_{i-1}) + φ(z) + ψ(x_i) },
 *              где x_i = k_i - k_{i-1} + y_i,
 *                  z  = (k_{i-1} + k_i + y_i) / 2.
 *
 * Ответ: Q_n(k_n).
 *
 * Особенность индексации таблиц:
 *   - φ задана в точках z = 0, 0.5, 1, 1.5, ...;
 *     в программе хранится в массиве phi, где phi[2*z] = φ(z);
 *   - ψ задана в целых точках x = 0, 1, 2, ...;
 *     в программе хранится в массиве psi, где psi[x] = ψ(x).
 *
 * Ограничение пространства состояний:
 *   запас k_i в конце i-го месяца не может превышать суммарный спрос
 *   за оставшиеся месяцы плюс конечный запас k_n. Иначе этот запас
 *   невозможно израсходовать к концу горизонта планирования.
 *
 * Сложность:
 *   - по времени: O(n * K^2), где K — максимальный рассматриваемый запас;
 *   - по памяти:  O(n * K), поскольку хранятся таблицы dp и parent.
 *   Для варианта 4 K мало, поэтому решение находится мгновенно.
 *
 * Формат результата:
 *   - таблицы j(z) и y(z);
 *   - таблицы Q_i(k_i) по каждому месяцу;
 *   - восстановленный оптимальный план;
 *   - проверка суммы затрат и ответ Q_n(k_n).
 *
 * Результат дополнительно сохраняется в файл output.txt.
 */

#include <iostream>
#include <fstream>
#include <sstream>
#include <vector>
#include <algorithm>
#include <iomanip>
#include <string>

using namespace std;

/** @brief Тип для стоимостей и значений DP. */
using ll = long long;

/** @brief Условная бесконечность для недостижимых состояний. */
const ll INF = (ll)1e18;

/**
 * @brief Форматирует величину z, заданную через 2*z.
 *
 * @param z2 Удвоенное значение z (целое число).
 * @return Строковое представление z с шагом 0,5:
 *         например, z2 = 5 -> "2,5", z2 = 4 -> "2".
 *
 * @details
 * В таблице φ(z) аргумент принимает значения 0, 0.5, 1, 1.5, ...
 * Чтобы не работать с числами с плавающей точкой, в DP хранится
 * удвоенный аргумент z2 = 2*z. Форматирование восстанавливает
 * исходную запись.
 */
string half(int z2) {
    if (z2 % 2 == 0) return to_string(z2 / 2);
    return to_string(z2 / 2) + ",5";
}

/**
 * @brief Точка входа программы.
 *
 * @details
 * Последовательно выполняет этапы решения:
 *   1. задаёт исходные данные варианта 4;
 *   2. вычисляет допустимые границы запасов по месяцам;
 *   3. заполняет таблицы динамического программирования;
 *   4. восстанавливает оптимальный план по массиву parent;
 *   5. формирует отчёт и выводит его в stdout и output.txt.
 *
 * @return 0 — решение найдено;
 * @return 1 — допустимого плана не существует.
 */
int main() {
    // ========================================================================
    // 1. Исходные данные варианта 4
    // ========================================================================

    /** @brief Количество месяцев в горизонте планирования. */
    const int n = 4;

    /**
     * @brief Расход (спрос) по месяцам.
     *
     * y[i] — расход в i-м месяце, i = 1..n.
     * Нулевой индекс не используется, чтобы обращаться по номеру месяца.
     * Значения взяты из блока «Вариант 4» файла ЛР4-варианты.xlsx.
     */
    vector<int> y(n + 1, 0);
    y[1] = 3;
    y[2] = 1;
    y[3] = 2;
    y[4] = 2;

    /** @brief Начальный запас. */
    const int k0 = 2;

    /** @brief Требуемый запас после последнего месяца. */
    const int kn = 0;

    /**
     * @brief Таблица затрат на хранение φ(z).
     *
     * В файле варианта обозначена как j(z).
     * phi[k] = φ(k / 2), то есть индекс массива равен 2*z:
     *   phi[0] = φ(0), phi[1] = φ(0.5), phi[2] = φ(1), ...
     *
     * Значения для варианта 4:
     *   j(0)=0, j(0.5)=7, j(1)=14, ..., j(6)=54.
     */
    vector<ll> phi = {0, 7, 14, 20, 26, 31, 36, 40, 44, 48, 51, 53, 54};

    /**
     * @brief Таблица затрат на пополнение ψ(x).
     *
     * В файле варианта обозначена как y(z).
     * psi[x] = ψ(x) для целого объёма пополнения x.
     *
     * Значения для варианта 4:
     *   y(0)=0, y(1)=27, y(2)=42, ..., y(6)=50.
     */
    vector<ll> psi = {0, 27, 42, 46, 48, 49, 50};

    // ========================================================================
    // 2. Допустимые границы запасов
    // ========================================================================

    /**
     * @brief Максимально допустимый запас в конце каждого месяца.
     *
     * maxK[i] — верхняя граница для k_i.
     *
     * В конце i-го месяца запас не может быть больше суммарного спроса
     * за все оставшиеся месяцы плюс конечный запас k_n. Иначе этот запас
     * некуда деть: к концу горизонта он должен стать равен k_n.
     *
     * Для i = n граница равна k_n.
     * Для i = 0 используется только начальный запас k0.
     */
    vector<int> maxK(n + 1, 0);
    maxK[n] = kn;
    for (int i = n - 1; i >= 1; i--)
        maxK[i] = maxK[i + 1] + y[i + 1];
    maxK[0] = k0;

    // ========================================================================
    // 3. Динамическое программирование
    // ========================================================================

    /**
     * @brief Таблицы DP и родительских состояний.
     *
     * dp[i][k]     — минимальные затраты за первые i месяцев при условии,
     *                что запас в конце i-го месяца равен k.
     * parent[i][k] — оптимальный запас в конце (i-1)-го месяца, из которого
     *                был достигнут запас k в конце i-го месяца.
     *
     * Массив parent нужен для восстановления оптимального плана.
     */
    vector<vector<ll>> dp(n + 1);
    vector<vector<int>> parent(n + 1);

    // База DP: до начала планирования запас равен k0 и затрат ещё нет.
    dp[0].assign(maxK[0] + 1, INF);
    dp[0][k0] = 0;

    /**
     * @details
     * Переходы по месяцам.
     *
     * Для каждого допустимого предыдущего запаса prev и каждого
     * допустимого текущего запаса cur вычисляем объём пополнения:
     *
     *   cur = prev + x - y[i]
     *   => x = cur - prev + y[i].
     *
     * Если x вне таблицы ψ, переход невозможен.
     *
     * Средний запас:
     *   z = (prev + cur + y[i]) / 2,
     * поэтому индекс в таблице φ равен:
     *   z2 = 2*z = prev + cur + y[i].
     *
     * Стоимость перехода:
     *   dp[i-1][prev] + φ(z) + ψ(x).
     *
     * Выбираем минимум по всем prev для каждого cur.
     */
    for (int i = 1; i <= n; i++) {
        dp[i].assign(maxK[i] + 1, INF);
        parent[i].assign(maxK[i] + 1, -1);

        for (int prev = 0; prev <= maxK[i - 1]; prev++) {
            // Недостижимое состояние пропускаем.
            if (dp[i - 1][prev] == INF) continue;

            for (int cur = 0; cur <= maxK[i]; cur++) {
                // Баланс запасов: cur = prev + x - y[i].
                int x = cur - prev + y[i];
                if (x < 0 || x >= (int)psi.size()) continue;

                // Удвоенный средний запас: z2 = 2*z.
                int z2 = prev + cur + y[i];
                if (z2 < 0 || z2 >= (int)phi.size()) continue;

                ll cost = dp[i - 1][prev] + phi[z2] + psi[x];

                // Релаксация: если нашли более дешёвый способ попасть в cur,
                // обновляем значение и запоминаем предка.
                if (cost < dp[i][cur]) {
                    dp[i][cur] = cost;
                    parent[i][cur] = prev;
                }
            }
        }
    }

    // Если конечное состояние недостижимо, допустимого плана нет.
    if (dp[n][kn] == INF) {
        cout << "Решение не найдено.\n";
        return 1;
    }

    // ========================================================================
    // 4. Восстановление оптимального плана
    // ========================================================================

    /**
     * @brief Параметры оптимального плана по месяцам.
     *
     * planPrev[i] — запас в конце (i-1)-го месяца;
     * planX[i]    — объём пополнения в i-м месяце;
     * planK[i]    — запас в конце i-го месяца;
     * planZ2[i]   — удвоенный средний запас z во i-м месяце.
     */
    vector<int> planPrev(n + 1), planX(n + 1), planK(n + 1), planZ2(n + 1);

    // Идём от конечного состояния назад по массиву parent.
    int cur = kn;
    for (int i = n; i >= 1; i--) {
        int prev = parent[i][cur];
        int x = cur - prev + y[i];

        planPrev[i] = prev;
        planX[i] = x;
        planK[i] = cur;
        planZ2[i] = prev + cur + y[i];

        cur = prev;
    }
    planK[0] = k0;

    // ========================================================================
    // 5. Формирование отчёта
    // ========================================================================

    /**
     * @brief Буфер отчёта.
     *
     * Отчёт собирается в ostringstream и затем одинаково выводится
     * в консоль и сохраняется в файл output.txt.
     */
    ostringstream out;
    out << "ЛР4. Дискретная задача управления запасами. Вариант 4\n";
    out << "k0 = " << k0 << ", k" << n << " = " << kn << "\n";
    out << "Расход по месяцам: ";
    for (int i = 1; i <= n; i++) out << "y" << i << " = " << y[i] << " ";
    out << "\n\n";

    // Печать таблицы φ(z) в исходных обозначениях j(z).
    out << "Таблица j(z):\n";
    for (int z2 = 0; z2 < (int)phi.size(); z2++) {
        out << "j(" << half(z2) << ") = " << phi[z2];
        if (z2 + 1 < (int)phi.size()) out << ", ";
    }
    out << "\n\n";

    // Печать таблицы ψ(x) в исходных обозначениях y(z).
    out << "Таблица y(z):\n";
    for (int x = 0; x < (int)psi.size(); x++) {
        out << "y(" << x << ") = " << psi[x];
        if (x + 1 < (int)psi.size()) out << ", ";
    }
    out << "\n\n";

    /**
     * @details
     * Для каждого месяца печатаем таблицу оптимальных переходов:
     * для каждого достижимого конечного запаса k показываем
     * лучший предыдущий запас, объём пополнения, средний запас z
     * и минимальные затраты Q_i(k).
     */
    for (int i = 1; i <= n; i++) {
        out << "Месяц " << i << ":\n";
        out << left
            << setw(10) << "k(i-1)"
            << setw(8) << "x_i"
            << setw(8) << "y_i"
            << setw(10) << "k_i"
            << setw(8) << "z"
            << setw(10) << "j(z)"
            << setw(10) << "y(x_i)"
            << setw(12) << "Q_i(k_i)" << "\n";
        out << string(76, '-') << "\n";

        bool any = false;
        for (int k = 0; k <= maxK[i]; k++) {
            if (dp[i][k] == INF) continue;
            any = true;

            int prev = parent[i][k];
            int x = k - prev + y[i];
            int z2 = prev + k + y[i];

            out << left
                << setw(10) << prev
                << setw(8) << x
                << setw(8) << y[i]
                << setw(10) << k
                << setw(8) << half(z2)
                << setw(10) << phi[z2]
                << setw(10) << psi[x]
                << setw(12) << dp[i][k] << "\n";
        }
        if (!any) out << "(нет допустимых состояний)\n";
        out << "\n";
    }

    // Итоговый оптимальный план.
    out << "Оптимальный план:\n";
    out << left
        << setw(6) << "i"
        << setw(10) << "k(i-1)"
        << setw(8) << "x_i"
        << setw(8) << "y_i"
        << setw(8) << "k_i"
        << setw(8) << "z"
        << setw(10) << "j(z)"
        << setw(10) << "y(x_i)" << "\n";
    out << string(58, '-') << "\n";

    // Суммируем затраты по месяцам и одновременно печатаем строки плана.
    ll total = 0;
    for (int i = 1; i <= n; i++) {
        ll stage = phi[planZ2[i]] + psi[planX[i]];
        total += stage;

        out << left
            << setw(6) << i
            << setw(10) << planPrev[i]
            << setw(8) << planX[i]
            << setw(8) << y[i]
            << setw(8) << planK[i]
            << setw(8) << half(planZ2[i])
            << setw(10) << phi[planZ2[i]]
            << setw(10) << psi[planX[i]] << "\n";
    }

    // Встроенная проверка: сумма затрат должна совпасть с dp[n][kn].
    out << "\nПроверка: сумма затрат = " << total << "\n";
    out << "Ответ: Q" << n << "(" << kn << ") = " << dp[n][kn] << " при ";
    for (int i = 1; i <= n; i++) {
        if (i > 1) out << ", ";
        out << "x" << i << " = " << planX[i];
    }
    out << ".\n";

    // ========================================================================
    // 6. Вывод результата
    // ========================================================================

    cout << out.str();

    ofstream fout("output.txt");
    fout << out.str();

    return 0;
}
