/**
 * @file main.cpp
 * @brief ЛР3. Сетевое планирование. Вариант 4.
 *
 * @details
 * Задача: дан проект из 18 работ. Для каждой работы известны:
 *   - длительность t_i;
 *   - список непосредственных предшественников.
 *
 * Требуется:
 *   1. проверить граф работ на ацикличность;
 *   2. построить топологический порядок;
 *   3. вычислить ранние сроки начала и окончания работ (ES / EF);
 *   4. вычислить поздние сроки начала и окончания работ (LS / LF);
 *   5. найти полные резервы времени R_i = LS_i - ES_i;
 *   6. определить критическое время Tкр и критический путь.
 *
 * Используемый алгоритм: CPM (Critical Path Method).
 *
 * Обозначения:
 *   ES_i (Earliest Start)  — самый ранний момент начала работы i;
 *   EF_i (Earliest Finish) — самый ранний момент окончания работы i;
 *   LS_i (Latest Start)    — самый поздний момент начала работы i,
 *                            при котором проект всё ещё завершается за Tкр;
 *   LF_i (Latest Finish)   — самый поздний момент окончания работы i;
 *   R_i  (Reserve)         — полный резерв времени работы i.
 *
 * Ключевые формулы:
 *   EF_i = ES_i + t_i
 *   ES_i = max { EF_p | p — непосредственный предшественник i }
 *   Tкр  = max { EF_i }
 *   LF_i = min { LS_s | s — непосредственный последователь i }
 *          (или Tкр, если у работы нет последователей)
 *   LS_i = LF_i - t_i
 *   R_i  = LS_i - ES_i
 *
 * Работа лежит на критическом пути, если R_i = 0.
 *
 * Сложность:
 *   - по времени: O(V + E), где V — число работ, E — число связей;
 *   - по памяти:  O(V + E), поскольку хранятся списки предшественников
 *                  и последователей.
 *
 * Формат результата:
 *   - таблица работ с t_i, предшественниками, ES, EF, LS, LF, R;
 *   - топологический порядок;
 *   - критическое время, список критических работ и один критический путь.
 *
 * Результат дополнительно сохраняется в файл output.txt.
 */

#include <iostream>
#include <fstream>
#include <sstream>
#include <vector>
#include <queue>
#include <algorithm>
#include <iomanip>
#include <string>

using namespace std;

/**
 * @brief Точка входа программы.
 *
 * @details
 * Последовательно выполняет все этапы CPM:
 *   1. задаёт исходные данные варианта 4;
 *   2. строит граф работ и списки последователей;
 *   3. выполняет топологическую сортировку (алгоритм Кана);
 *   4. делает прямой проход для ES / EF;
 *   5. делает обратный проход для LS / LF;
 *   6. вычисляет резервы и восстанавливает критический путь;
 *   7. формирует текстовый отчёт и пишет его в stdout и output.txt.
 *
 * @return 0 — успешное решение;
 * @return 1 — в графе обнаружен цикл, проект некорректен.
 */
int main() {
    // ========================================================================
    // 1. Исходные данные варианта 4
    // ========================================================================

    /**
     * @brief Количество работ в проекте.
     *
     * Работы нумеруются с 1 по n включительно. Нулевой индекс в массивах
     * оставлен пустым, чтобы обращаться к работе по её номеру напрямую:
     * dur[i], pred[i], es[i] и т.д.
     */
    const int n = 18;

    /**
     * @brief Длительности работ.
     *
     * dur[i] — время выполнения работы i (i = 1..18).
     * Значения взяты из блока «Вариант 4» файла ЛР3-варианты.xlsx.
     */
    vector<int> dur(n + 1, 0);
    int d[] = {0, 16, 8, 9, 14, 16, 11, 7, 12, 15, 16, 12, 13, 16, 14, 14, 15, 16, 14};
    for (int i = 1; i <= n; i++) dur[i] = d[i];

    /**
     * @brief Списки непосредственных предшественников.
     *
     * pred[i] содержит номера работ, которые должны быть завершены
     * до начала работы i. Пустой список означает, что работа может
     * начинаться с нулевого момента времени.
     *
     * Данные соответствуют варианту 4: три строки «Опирается на»
     * из файла ЛР3-варианты.xlsx.
     */
    vector<vector<int>> pred(n + 1);
    pred[1] = {};
    pred[2] = {};
    pred[3] = {1};
    pred[4] = {2};
    pred[5] = {2, 4};
    pred[6] = {3, 4};
    pred[7] = {6, 5};
    pred[8] = {5, 6, 4};
    pred[9] = {6, 4, 5};
    pred[10] = {8, 9};
    pred[11] = {9, 7};
    pred[12] = {9};
    pred[13] = {11, 12};
    pred[14] = {11, 12, 10};
    pred[15] = {11};
    pred[16] = {15, 13};
    pred[17] = {14, 15};
    pred[18] = {13, 15};

    // ========================================================================
    // 2. Построение графа работ
    // ========================================================================

    /**
     * @brief Списки непосредственных последователей.
     *
     * succ[p] содержит работы, которые зависят от работы p.
     * Строится один раз за O(E) и используется в обратном проходе CPM.
     */
    vector<vector<int>> succ(n + 1);

    /**
     * @brief Входящие степени вершин для алгоритма Кана.
     *
     * indeg[v] изначально равно количеству предшественников работы v.
     * В процессе топологической сортировки значение уменьшается
     * при обработке каждого предшественника.
     */
    vector<int> indeg(n + 1, 0);

    for (int v = 1; v <= n; v++) {
        // Входящая степень — число непосредственных предшественников.
        indeg[v] = (int)pred[v].size();

        // Для каждого предшественника p добавляем v в его список потомков.
        for (int p : pred[v]) succ[p].push_back(v);
    }

    // ========================================================================
    // 3. Топологическая сортировка (алгоритм Кана)
    // ========================================================================

    /**
     * @details
     * Алгоритм Кана:
     *   1. помещаем в очередь все вершины с indeg = 0;
     *   2. извлекаем вершину, добавляем её в топологический порядок;
     *   3. уменьшаем indeg всех её последователей;
     *   4. если indeg последователя стал равен 0, добавляем его в очередь.
     *
     * Если после завершения работы очереди в порядке оказалось меньше n
     * вершин, значит, в графе есть цикл, и корректное расписание построить
     * невозможно.
     */
    queue<int> q;
    for (int v = 1; v <= n; v++)
        if (indeg[v] == 0) q.push(v);

    /** @brief Топологический порядок работ. */
    vector<int> topo;
    while (!q.empty()) {
        int v = q.front();
        q.pop();
        topo.push_back(v);

        for (int s : succ[v])
            if (--indeg[s] == 0) q.push(s);
    }

    // Проверка ацикличности: в корректном проекте все n работ должны
    // попасть в топологический порядок.
    if ((int)topo.size() != n) {
        cout << "Ошибка: в графе есть цикл.\n";
        return 1;
    }

    // ========================================================================
    // 4. Прямой проход: ранние сроки ES / EF
    // ========================================================================

    /**
     * @brief Ранние сроки начала и окончания работ.
     *
     * es[v] — Earliest Start работы v;
     * ef[v] — Earliest Finish работы v.
     *
     * Работы обрабатываются в топологическом порядке, поэтому к моменту
     * вычисления es[v] все ef[p] для предшественников уже известны.
     */
    vector<int> es(n + 1, 0), ef(n + 1, 0);

    for (int v : topo) {
        // Работа может начаться только после завершения ВСЕХ предшественников,
        // поэтому берём максимум из их ранних окончаний.
        int start = 0;
        for (int p : pred[v]) start = max(start, ef[p]);

        es[v] = start;
        ef[v] = start + dur[v];
    }

    /**
     * @brief Критическое время проекта.
     *
     * Проект завершён, когда завершены все работы, поэтому Tкр — это
     * максимальный ранний срок окончания среди всех работ.
     */
    int Tkp = 0;
    for (int v = 1; v <= n; v++) Tkp = max(Tkp, ef[v]);

    // ========================================================================
    // 5. Обратный проход: поздние сроки LS / LF
    // ========================================================================

    /**
     * @brief Поздние сроки начала и окончания работ.
     *
     * ls[v] — Latest Start работы v;
     * lf[v] — Latest Finish работы v.
     *
     * Обратный проход идёт по топологическому порядку с конца. Для конечных
     * работ (без последователей) позднее окончание равно Tкр. Для остальных
     * работ позднее окончание равно минимуму поздних начал последователей:
     * работа должна закончиться до того, как начнётся любой её последователь.
     */
    vector<int> ls(n + 1, 0), lf(n + 1, 0);

    for (int idx = n - 1; idx >= 0; idx--) {
        int v = topo[idx];

        // По умолчанию работа может закончиться в момент Tкр.
        int finish = Tkp;

        // Если есть последователи, нужно закончить до самого раннего
        // из их поздних начал.
        for (int s : succ[v]) finish = min(finish, ls[s]);

        lf[v] = finish;
        ls[v] = finish - dur[v];
    }

    // ========================================================================
    // 6. Резервы времени
    // ========================================================================

    /**
     * @brief Полный резерв времени работы.
     *
     * reserve[v] = LS_v - ES_v = LF_v - EF_v.
     *
     * Резерв показывает, на сколько можно задержать работу без увеличения
     * общего времени проекта. Работы с нулевым резервом являются
     * критическими.
     */
    vector<int> reserve(n + 1, 0);
    for (int v = 1; v <= n; v++) reserve[v] = ls[v] - es[v];

    // ========================================================================
    // 7. Восстановление критического пути
    // ========================================================================

    /**
     * @details
     * Критический путь — это цепочка работ с нулевым резервом, которая
     * начинается в момент 0 и заканчивается в момент Tкр.
     *
     * Сначала выбираем критическую работу, которая заканчивается в Tкр.
     * Затем идём назад по критическим связям: для текущей работы cur ищем
     * такого предшественника p, что:
     *   - R_p = 0 (предшественник тоже критический);
     *   - EF_p = ES_cur (между ними нет временного зазора).
     *
     * Условие EF_p = ES_cur гарантирует, что связь p -> cur лежит на
     * критическом пути, а не просто соединяет две критические работы.
     */
    int end = -1;
    for (int v = 1; v <= n; v++) {
        if (reserve[v] == 0 && ef[v] == Tkp) {
            end = v;
            break;
        }
    }

    /** @brief Один критический путь в порядке от начала проекта к концу. */
    vector<int> path;

    int cur = end;
    while (cur != -1) {
        path.push_back(cur);

        // Ищем критического предшественника, который заканчивается
        // ровно в момент начала текущей работы.
        int next = -1;
        for (int p : pred[cur]) {
            if (reserve[p] == 0 && ef[p] == es[cur]) {
                next = p;
                break;
            }
        }
        cur = next;
    }

    // Шли от конца к началу — разворачиваем путь.
    reverse(path.begin(), path.end());

    // ========================================================================
    // 8. Формирование отчёта
    // ========================================================================

    /**
     * @brief Буфер отчёта.
     *
     * Сначала весь отчёт собирается в ostringstream, а затем одинаково
     * выводится в консоль и сохраняется в output.txt. Так гарантируется,
     * что консоль и файл содержат идентичный текст.
     */
    ostringstream out;
    out << "ЛР3. Сетевое планирование. Вариант 4\n";
    out << "Количество работ: " << n << "\n\n";

    // Заголовок таблицы работ.
    out << left
        << setw(6) << "№"
        << setw(6) << "t_i"
        << setw(24) << "Опирается на"
        << setw(6) << "ES"
        << setw(6) << "EF"
        << setw(6) << "LS"
        << setw(6) << "LF"
        << setw(6) << "R" << "\n";
    out << string(56, '-') << "\n";

    // Таблица по каждой работе: длительность, предшественники и сроки.
    for (int v = 1; v <= n; v++) {
        string p;
        for (int x : pred[v]) p += to_string(x) + " ";

        out << left
            << setw(6) << v
            << setw(6) << dur[v]
            << setw(24) << p
            << setw(6) << es[v]
            << setw(6) << ef[v]
            << setw(6) << ls[v]
            << setw(6) << lf[v]
            << setw(6) << reserve[v] << "\n";
    }

    // Служебная информация о ходе решения.
    out << "\nТопологический порядок: ";
    for (int v : topo) out << v << " ";
    out << "\n";

    out << "Критическое время Tкр = " << Tkp << "\n";

    out << "Критические работы (R = 0): ";
    for (int v = 1; v <= n; v++)
        if (reserve[v] == 0) out << v << " ";
    out << "\n";

    out << "Критический путь: ";
    for (int i = 0; i < (int)path.size(); i++) {
        if (i) out << " -> ";
        out << path[i];
    }
    out << "\n";

    // Сумма длительностей работ критического пути должна совпадать с Tкр.
    // Это удобная встроенная проверка корректности.
    int pathLen = 0;
    for (int v : path) pathLen += dur[v];
    out << "Длина критического пути: " << pathLen << "\n";

    // ========================================================================
    // 9. Вывод результата
    // ========================================================================

    cout << out.str();

    ofstream fout("output.txt");
    fout << out.str();

    return 0;
}
