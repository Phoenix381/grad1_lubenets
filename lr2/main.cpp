void print_matrix(ostream &out, const vector<vector<int>> &vctr){
    for(auto r:vctr){
        for(size_t j = 0; j < r.size(); ++j){
            if(j) out<<" ";
            out<<r[j];
        }
        out<<'\n';
    }
}

bool is_digit(char ch) {
    return ch <= 57 && ch >= 48;
}

void read_matrix(vector<vector<int>> *vctr) {
    vctr->clear();

    string s;
    while (getline(cin, s)) {
        if (s.find_first_not_of(" \t\r") == string::npos) {
            if (!vctr->empty()) return;
            else continue;
        }
        
        if (!s.empty() && s[0] == ':') continue;

        (*vctr).push_back(vector<int>());

        vector<char> curr;
        bool is_dev = false;

        for (int i = 0; i < (int)s.size(); i++)
        {
            if (is_digit(s[i]) || s[i] == '.') curr.push_back(s[i]);

            if (s[i] == '/') {
                (*vctr).back().push_back(stoi(string(curr.begin(), curr.end())));
                is_dev = true;
                curr.clear();
                continue;
            }

            if (s[i] == ' ' || i == (int)s.size() - 1) {
                if (curr.empty()) { is_dev = false; continue; }
                if (is_dev) {
                    is_dev = false;
                    (*vctr).back().back() /= stoi(string(curr.begin(), curr.end()));
                }
                else {
                    (*vctr).back().push_back(stoi(string(curr.begin(), curr.end())));
                }
                curr.clear();
            }
        }
    }
}

vector<int> D(const vector<vector<int>>& matrix) {
    size_t rows = matrix.size();
    size_t cols = matrix[0].size();

    vector<int> res(cols);
    for (size_t j = 0; j < cols; j++) {
        int col_max = matrix[0][j];
        for (size_t i = 1; i < rows; i++)
            if (matrix[i][j] > col_max) col_max = matrix[i][j];
        res[j] = col_max;
    }
    return res;
}

vector<vector<int>> calc_R(const vector<vector<int>>& matrix) {
    vector<int> d = D(matrix);
    vector<vector<int>> res = matrix;
    for (int i = 0; i < res[0].size(); i++)
    {
        for (int j = 0; j < res.size(); j++)
        {
            res[j][i] = d[i]-res[j][i];
        }
    }
    return res;
}

pair<int,double> find_max(const vector<double>& w){
    auto el = max_element(w.begin(),w.end());
    return {(el - w.begin()) + 1, *el};
}

pair<int,double> find_min(const vector<double>& w){
    auto el = min_element(w.begin(),w.end());
    return {(el - w.begin()) + 1, *el};
}

pair<int,double> вальда(const vector<vector<int>>& matrix){
    pair<int,double> ans = {1,*min_element(matrix[0].begin(),matrix[0].end())};
    for (int i = 0; i < matrix.size(); i++){
        double el = *min_element(matrix[i].begin(),matrix[i].end());
        if (ans.second<el)ans = {i+1,el};
    }
    return ans;
}

pair<int,double> сэвиджа(const vector<vector<int>>& matrix){
    vector<vector<int>> R = calc_R(matrix);
    pair<int,double> ans = {1,*max_element(R[0].begin(),R[0].end())};
    for (int i = 0; i < R.size(); i++){
        double el = *max_element(R[i].begin(),R[i].end());
        if (ans.second>el)ans = {i+1,el};
    }
    return ans;
}

// [0,m) -> M [m,2m) -> N
pair<int,double> гурвиц(const vector<vector<int>>& matrix){
    vector<int> ans(2*matrix.size());

    for (int i = 0; i < ans.size(); i++)
    {
        if (i<matrix.size())ans[i] = *min_element(matrix[i].begin(),matrix[i].end());
        else ans[i] = *max_element(matrix[i-matrix.size()].begin(),matrix[i-matrix.size()].end());
    }
    vector<double> w(matrix.size());
    for (int i = 0; i < matrix.size(); i++)
    {
        w[i] = (ans[i] + ans[i+matrix.size()])/2.0;
    }
    return find_max(w);
}

pair<int,double> лаплас(const vector<vector<int>>& matrix){
    vector<double> w(matrix.size());
    for (int i = 0; i < w.size(); i++)
    {
        w[i] = accumulate(matrix[i].begin(),matrix[i].end(),0.0)/matrix[0].size();
    }
    return find_max(w);
}

pair<int,double> ходж(const vector<vector<int>>& matrix){
    vector<double> w(matrix.size());
    for (int i = 0; i < matrix.size(); i++)
    {
        w[i] = (accumulate(matrix[i].begin(),matrix[i].end(),0.0)/matrix[0].size() + *min_element(matrix[i].begin(),matrix[i].end()))/2;
    }

    return find_max(w);
}

string decimal_comma(double value) {
    ostringstream ss;
    ss << setprecision(10) << value;
    string s = ss.str();
    replace(s.begin(), s.end(), '.', ',');
    return s;
}

void print_values(ostream &out, const string &title, const vector<double> &v) {
    out << title << "\n";
    for (size_t i = 0; i < v.size(); ++i)
        out << "  стратегия " << i + 1 << ": " << decimal_comma(v[i]) << "\n";
}

void solve() {
    freopen("input.txt", "r", stdin);

    ostringstream report;

    vector<vector<int>> A;
    read_matrix(&A);

    report << "Матрица A:\n";
    print_matrix(report, A);

    vector<int> d = D(A);
    report << "\nМаксимумы по столбцам D:\n  ";
    for (size_t j = 0; j < d.size(); ++j) {
        if (j) report << " ";
        report << d[j];
    }
    report << "\n";

    vector<vector<int>> R = calc_R(A);
    report << "\nМатрица рисков R:\n";
    print_matrix(report, R);

    size_t rows = A.size();
    size_t cols = A[0].size();
    vector<double> wald(rows), savage(rows), hurwitz(rows), laplace(rows), hodges(rows);

    for (size_t i = 0; i < rows; ++i) {
        double mn = *min_element(A[i].begin(), A[i].end());
        double mx = *max_element(A[i].begin(), A[i].end());
        double avg = accumulate(A[i].begin(), A[i].end(), 0.0) / cols;
        wald[i] = mn;
        savage[i] = *max_element(R[i].begin(), R[i].end());
        hurwitz[i] = (mn + mx) / 2.0;
        laplace[i] = avg;
        hodges[i] = (avg + mn) / 2.0;
    }

    report << "\n";
    print_values(report, "Критерий Вальда (минимум по строке):", wald);
    print_values(report, "\nКритерий Сэвиджа (максимум по строке матрицы рисков):", savage);
    print_values(report, "\nКритерий Гурвица (λ = 1/2):", hurwitz);
    print_values(report, "\nКритерий Байеса – Лапласа (среднее по строке):", laplace);
    print_values(report, "\nКритерий Ходжа – Лемана (ν = 1/2):", hodges);

    pair<int,double> q1 = find_max(wald);
    pair<int,double> q2 = find_min(savage);
    pair<int,double> q3 = find_max(hurwitz);
    pair<int,double> q4 = find_max(laplace);
    pair<int,double> q5 = find_max(hodges);

    report << "\nОтвет: решения игры следующие:\n";
    report << "по критерию Вальда: " << decimal_comma(q1.second)
           << " при стратегии " << q1.first << ",\n";
    report << "по критерию Сэвиджа: " << decimal_comma(q2.second)
           << " при стратегии " << q2.first << ",\n";
    report << "по критерию Гурвица: " << decimal_comma(q3.second)
           << " при стратегии " << q3.first << ",\n";
    report << "по критерию Байеса – Лапласа: " << decimal_comma(q4.second)
           << " при стратегии " << q4.first << ",\n";
    report << "по критерию Ходжа – Лемана: " << decimal_comma(q5.second)
           << " при стратегии " << q5.first << ".\n";

    cout << report.str();

    ofstream fout("output.txt");
    fout << report.str();
}

